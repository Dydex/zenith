"""Replays the six vaults of the main sample with Zenith's circuit breaker. Standard library only, deterministic.

A vault's value per share is compared with a passive full-range position in the same pool, interval by interval,
from evidence/data (daily samples). The breaker tracks the best that ratio has reached; once the ratio falls a set
share below that best, the vault is moved to passive. From then on it earns what the passive position earns, after a
one-off rebalancing cost charged on the whole vault (an assumption: the swap fee and price impact of bringing a
one-sided position back to full range).

  python3 evidence/scripts/breaker.py

Writes evidence/BREAKER.md.
"""
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import analyze  # noqa: E402

LEVELS = [0.03, 0.05, 0.10]
REBALANCING_COST = 0.005


def replay(rows, level):
    """Relative value against passive at the end, with and without the breaker, and the interval it tripped in."""
    ratio = peak = 1.0
    tripped_at = None
    without = 1.0
    for i, row in enumerate(rows):
        step = (1 + row["total"]) / (1 + row["passive_total"])
        without *= step
        if tripped_at is None:
            ratio *= step
            peak = max(peak, ratio)
            if ratio < peak * (1 - level):
                tripped_at = i
                ratio *= 1 - REBALANCING_COST
        # After the trip the vault is passive: its ratio to passive stays where it was.
    return without, ratio, tripped_at


def main():
    study, pools, states, times = analyze.load()
    when = dict(times)
    chosen = analyze.study_sample(study, pools, states, step=analyze.DAY)
    lines = [
        "# The circuit breaker on mainnet vaults",
        "",
        "Generated by `scripts/breaker.py`. Do not edit by hand.",
        "",
        "Each vault of the main sample, replayed with Zenith's breaker on daily samples. The ratio is the vault's",
        "value per share over a passive full-range position's, both starting at 1. At a trip the vault moves to passive",
        f"and pays a one-off rebalancing cost of {REBALANCING_COST:.1%} of its value, an assumption.",
        "",
        "| Vault | Days | As it ran, vs passive | " + " | ".join(f"Breaker at {x:.0%}" for x in LEVELS) + " |",
        "|---|--:|--:|" + "--:|" * len(LEVELS),
    ]
    summary = {x: [] for x in LEVELS}
    for result, rows in chosen:
        cells = []
        without = None
        for level in LEVELS:
            without, with_breaker, tripped_at = replay(rows, level)
            day = "no trip" if tripped_at is None else f"day {tripped_at + 1}"
            cells.append(f"{with_breaker - 1:+.1%} ({day})")
            summary[level].append((without, with_breaker))
        name = f"`{result['vault'][:6]}` {result['pool']}"
        lines.append(f"| {name} | {len(rows)} | {without - 1:+.1%} | " + " | ".join(cells) + " |")

    lines += ["", "## Summary", ""]
    for level in LEVELS:
        pairs = summary[level]
        helped = sum(1 for a, b in pairs if b > a)
        worst_without = min(a for a, _ in pairs) - 1
        worst_with = min(b for _, b in pairs) - 1
        lines.append(
            f"- **Breaker at {level:.0%}:** better than as run for {helped} of {len(pairs)} vaults; the worst vault "
            f"against passive goes from {worst_without:+.1%} to {worst_with:+.1%}."
        )
    lines += [
        "",
        "## Limits",
        "",
        "- Daily samples: a real breaker checks every keeper tick (about 18 minutes), so a trip here can overshoot its",
        "  level by up to a day's move.",
        "- The rebalancing cost is an assumption, not measured; in a thin pool Zenith rebalances over several steps and",
        "  can pay more.",
        "- Total return is compared, so a trip can follow bad luck as well as a bad range. The breaker never decides pay.",
        "- Six vaults; the same limits as the main study apply.",
    ]
    (analyze.ROOT / "BREAKER.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
